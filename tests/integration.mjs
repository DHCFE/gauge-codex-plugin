const dir=join(home,'sessions/2026/10/01');mkdirSync(dir,{recursive:true});
const archived=join(home,'archived_sessions');mkdirSync(archived);
let time=Date.now()-30000;
const end=Date.now()+3*86400000, start=end-7*86400000;
const iso=n=>new Date(n).toISOString();
const tokens={input_tokens:1000,cached_input_tokens:200,cache_write_input_tokens:100,output_tokens:100,reasoning_output_tokens:40,total_tokens:1100};
const row=(type,payload,at=time)=>({timestamp:iso(at),type,payload});
const request=(id,rid,at=time)=>row('token_usage_record',{thread_id:id,turn_id:'turn',response_id:rid,model:'gpt-6.1-sol',usage:tokens},at);
function transcript(id,metadata={},requests=[]) {
  const path=join(dir,'rollout-test-'+id+'.jsonl');
  writeFileSync(path,[row('session_meta',{id,model_provider:'openai',account_id:'account-a',billing_pool_id:'codex',cwd:'/synthetic/project',...metadata}),row('turn_context',{turn_id:'turn',model:'gpt-6.1-sol'}),...requests].map(JSON.stringify).join('\n')+'\n');
  return path;
}
const root=transcript('root',{},[request('root','old',start-1),request('root','current',start),request('root','end',end)]);
transcript('child',{source:{subagent:{thread_spawn:{parent_thread_id:'root'}}}},[request('root','current',start),request('child','child-own')]);
transcript('fork',{forked_from_id:'root'},[request('root','current',start),request('fork','fork-own')]);
transcript('other',{account_id:'account-b'},[request('other','other')]);
transcript('anonymous',{account_id:null},[request('anonymous','anon',start-1)]);
writeFileSync(join(archived,'rollout-copy-root.jsonl'),String(execFileSync('/bin/cat',[root])));
const env={...process.env,CODEX_HOME:home,TOKENLENS_DATA:data,TOKENLENS_ROOT:resolve('plugin')};
