  assert.ok(q.estimate.warnings.includes('local_history_external_coverage_unknown'));
  assert.equal(q.cycleUsage.total.requestCount,3,'exact cycle includes start, excludes end and previous history');
  assert.equal(q.cycleUsage.period.startAt,start);
  assert.equal(q.cycleUsage.period.endAt,end);
  const percentageScope=createIntegration({dataDir:join(data,'percentage'),readAccount,readQuota:async()=>rawQuota(),estimateCapacity:estimateWeeklyCapacity,now:()=>new Date(time)});
