const rawQuota=()=>normalizeQuotaSnapshot({source:'synthetic-official-rpc',account:{accountId:'account-a'},updatedAt:iso(time),rateLimitsByLimitId:{codex:{secondary:{usedPercent:25,windowDurationMins:WEEK_MINUTES,resetsAt:end/1000}}}});
